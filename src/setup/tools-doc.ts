import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export type ToolDoc = {
  name: string;
  title: string;
  description: string;
  readOnly: boolean;
  destructive: boolean;
  openWorld: boolean;
};

export function parseToolDocs(toolsDir: string): ToolDoc[] {
  const files = readdirSync(toolsDir)
    .filter((f) => f.endsWith(".ts"))
    .sort();
  const docs: ToolDoc[] = [];
  for (const file of files) {
    const src = readFileSync(join(toolsDir, file), "utf8");
    const match = src.match(
      /server\.registerTool\(\s*"([^"]+)"\s*,\s*\{[\s\S]*?title:\s*"([^"]*)"[\s\S]*?description:\s*"((?:\\.|[^"\\])*)"/,
    );
    if (!match?.[1] || match[2] === undefined || match[3] === undefined) {
      continue;
    }
    docs.push({
      name: match[1],
      title: match[2],
      description: match[3].replaceAll('\\"', '"'),
      readOnly: /readOnlyHint:\s*true/.test(src),
      destructive: /destructiveHint:\s*true/.test(src),
      openWorld: /openWorldHint:\s*true/.test(src),
    });
  }
  docs.sort((a, b) => a.name.localeCompare(b.name));
  return docs;
}

export function renderToolsMarkdown(docs: ToolDoc[]): string {
  const lines = [
    "<!-- Generated by scripts/gen-tools-doc.ts. Do not edit by hand. -->",
    "",
    "# MCP tools",
    "",
    "The host AI generates answers, quiz questions, and plans. CourseCopilot only fetches, indexes, retrieves, and stores learning state. No LLM API key.",
    "",
    "| Tool | Title | RO | Role |",
    "|---|---|---|---|",
  ];
  for (const doc of docs) {
    const ro = doc.readOnly ? "yes" : doc.destructive ? "destructive" : "no";
    const desc = doc.description.replaceAll("|", "\\|");
    lines.push(`| \`${doc.name}\` | ${doc.title} | ${ro} | ${desc} |`);
  }
  lines.push(
    "",
    "Resources: `coursecopilot://courses`, `coursecopilot://document/{id}`, `coursecopilot://course/{id}/outline`, `coursecopilot://course/{id}/mastery`.",
    "",
    "Prompts: `quiz_me_on_misses`, `quiz_me`, `study_session`, `exam_prep`, `explain_with_sources`, `add_my_course`, `whats_due`, `get_started`.",
    "",
  );
  return lines.join("\n");
}
